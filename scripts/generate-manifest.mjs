import { readdir, writeFile, mkdir } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const publicAssets = join(root, 'public', 'assets')

const STAGES = [
  { key: 'backgrounds', label: 'Background' },
  { key: 'middle', label: 'Middle' },
  { key: 'foreground', label: 'Foreground' },
]

// Map folder name to stage key
const FOLDER_TO_STAGE = {
  backgrounds: 'background',
  middle: 'middle',
  foreground: 'foreground',
}

function extractCategoryName(folderName) {
  // Convert folder name like "logo_bg_1" to "Background 1"
  // or "logo_middle_1" to "Middle 1"
  // or "logo_foreground" to "Foreground"
  const cleaned = folderName
    .replace(/^logo_/, '') // Remove "logo_" prefix
    .replace(/_(\d+)$/, ' $1') // Convert "bg_1" to "bg 1"
    .replace(/_/g, ' ') // Replace remaining underscores with spaces

  // Capitalize first letter of each word
  return cleaned
    .split(' ')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ')
}

async function listSubfolders(baseDir) {
  try {
    const entries = await readdir(baseDir, { withFileTypes: true })
    return entries
      .filter(e => e.isDirectory())
      .map(e => e.name)
      .sort()
  } catch {
    return []
  }
}

async function listPngs(folderPath) {
  try {
    const files = await readdir(folderPath)
    return files
      .filter((f) => f.toLowerCase().endsWith('.png'))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
  } catch {
    return []
  }
}

async function main() {
  const categories = {
    background: [],
    middle: [],
    foreground: [],
  }

  for (const { key } of STAGES) {
    const stageDir = join(publicAssets, key)
    const subfolders = await listSubfolders(stageDir)

    for (const subfolder of subfolders) {
      const subfolderPath = join(stageDir, subfolder)
      const files = await listPngs(subfolderPath)

      if (files.length > 0) {
        const stageKey = FOLDER_TO_STAGE[key]
        categories[stageKey].push({
          id: subfolder,
          name: extractCategoryName(subfolder),
          path: `/assets/${key}/${subfolder}`,
          assets: files.map(filename => ({
            id: `${subfolder}_${filename.replace(/\.png$/i, '')}`,
            filename,
            path: `/assets/${key}/${subfolder}/${filename}`,
          })),
        })
      }
    }

    console.log(`  ${key}: ${categories[FOLDER_TO_STAGE[key]].length} category folder(s)`)
  }

  const outPath = join(root, 'src', 'data', 'assetManifest.ts')
  await mkdir(dirname(outPath), { recursive: true })

  const content = `// Auto-generated by scripts/generate-manifest.mjs — do not edit manually
import type { StageCategories } from '../types'

export const assetManifest: StageCategories = ${JSON.stringify(categories, null, 2)} as const
`
  await writeFile(outPath, content, 'utf8')
  console.log('Asset manifest generated at src/data/assetManifest.ts')
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})